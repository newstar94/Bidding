import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';

// Build views/vendor/lucide/lucide-subset.js from the pinned, audited Lucide
// UMD (ISC). The full library is ~409 KB, almost all icon geometry; the app
// uses a small fraction. The subset keeps Lucide's own replace semantics and
// lazily falls back to the full library when it meets an unknown icon name
// (e.g. one built at runtime), so no icon can silently disappear.

const FULL = 'views/vendor/lucide/lucide.min.js';
const OUT = 'views/vendor/lucide/lucide-subset.js';
const VERSION_FILE = 'frontend/shared/lucideSubsetVersion.js';

const context = {};
vm.runInNewContext(fs.readFileSync(FULL, 'utf8'), context);
const icons = context.lucide.icons;
const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, _prefix, letter) => letter.toUpperCase());
const kebabNames = new Map(
  Object.keys(icons).map((key) => [
    key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Za-z])([0-9])/g, '$1-$2').toLowerCase(),
    key,
  ]),
);

function walk(directory, extensions, files = []) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== 'vendor' && entry.name !== 'node_modules') walk(full, extensions, files);
    } else if (extensions.some((extension) => entry.name.endsWith(extension))) {
      files.push(full);
    }
  }
  return files;
}

// Over-include on purpose: every quoted literal that is exactly a Lucide name.
const used = new Set();
for (const file of [...walk('frontend', ['.js']), ...walk('views', ['.html'])]) {
  const source = fs.readFileSync(file, 'utf8');
  for (const match of source.matchAll(/["'`]([a-z][a-z0-9-]{1,40})["'`]/g)) {
    const key = kebabNames.get(match[1]) || (icons[pascal(match[1])] ? pascal(match[1]) : null);
    if (key) used.add(key);
  }
  for (const match of source.matchAll(/data-lucide=\\?["']([a-z0-9-]+)\\?["']/g)) {
    const key = icons[pascal(match[1])] ? pascal(match[1]) : kebabNames.get(match[1]);
    if (key) used.add(key);
  }
}

const subset = Object.fromEntries([...used].sort().map((key) => [key, icons[key]]));
const body = `/*! Lucide ${'1.21.0'} subset (ISC) - generated by scripts/generate_lucide_subset.mjs. Do not edit. */
(function (global) {
  "use strict";
  var DEFAULTS = {xmlns:"http://www.w3.org/2000/svg",width:24,height:24,viewBox:"0 0 24 24",fill:"none",stroke:"currentColor","stroke-width":2,"stroke-linecap":"round","stroke-linejoin":"round"};
  var ICONS = ${JSON.stringify(subset)};
  function build(node) {
    var el = document.createElementNS("http://www.w3.org/2000/svg", node[0]);
    Object.keys(node[1]).forEach(function (k) { if (k !== "key") el.setAttribute(k, String(node[1][k])); });
    (node[2] || []).forEach(function (child) { el.appendChild(build(child)); });
    return el;
  }
  function toPascal(name) {
    var camel = name.replace(/^([A-Z])|[\\s-_]+(\\w)/g, function (m, a, b) { return b ? b.toUpperCase() : a.toLowerCase(); });
    return camel.charAt(0).toUpperCase() + camel.slice(1);
  }
  function hasAccessibleName(attrs) {
    for (var k in attrs) if (k.indexOf("aria-") === 0 || k === "role" || k === "title") return true;
    return false;
  }
  function classes(value) {
    if (typeof value === "string") return value.split(" ");
    return Array.isArray(value) ? value : [];
  }
  function replace(el, icons, nameAttr, extra) {
    var name = el.getAttribute(nameAttr);
    if (name == null) return true;
    var nodes = icons[toPascal(name)];
    if (!nodes) return false;
    var own = {};
    Array.prototype.forEach.call(el.attributes, function (a) { own[a.name] = a.value; });
    var attrs = Object.assign({}, DEFAULTS, {"data-lucide": name}, hasAccessibleName(own) ? {} : {"aria-hidden": "true"}, extra, own);
    var list = ["lucide", "lucide-" + name].concat(classes(own["class"]), classes(extra["class"]));
    attrs["class"] = list.filter(function (c, i, all) { return c && c.trim() !== "" && all.indexOf(c) === i; }).join(" ").trim();
    var svg = build(["svg", attrs, nodes]);
    if (el.parentNode) el.parentNode.replaceChild(svg, el);
    return true;
  }
  var fullLoading = null;
  function loadFull() {
    // The application owns script loading so the Trusted Types policy and
    // the fixed full-library URL stay in first-party code.
    if (fullLoading) return fullLoading;
    var loader = global.__bfLoadFullLucide;
    if (typeof loader !== "function") return Promise.reject(new Error("Full Lucide loader unavailable"));
    fullLoading = Promise.resolve(loader()).then(function (full) {
      if (!full || !full.icons) throw new Error("Full Lucide library did not load");
      Object.assign(ICONS, full.icons);
    });
    return fullLoading;
  }
  function createIcons(options) {
    options = options || {};
    var nameAttr = options.nameAttr || "data-lucide";
    var root = options.root || document;
    var extra = options.attrs || {};
    var missing = false;
    Array.prototype.forEach.call(root.querySelectorAll("[" + nameAttr + "]"), function (el) {
      if (el.namespaceURI === "http://www.w3.org/2000/svg" && el.tagName.toLowerCase() === "svg") return;
      if (!replace(el, options.icons || ICONS, nameAttr, extra)) missing = true;
    });
    if (missing) {
      loadFull().then(function () { createIcons(options); }, function (error) { console.warn(error); });
    }
  }
  global.lucide = {createIcons: createIcons, icons: ICONS, __bfLucideSubset: true};
})(typeof globalThis !== "undefined" ? globalThis : this);
`;
const version = createHash('sha256').update(body).digest('hex').slice(0, 16);
const versionModule = `// Generated by scripts/generate_lucide_subset.mjs.\nexport const LUCIDE_SUBSET_URL = "/vendor/lucide/lucide-subset.js?v=${version}";\n`;
for (const [file, content] of [[OUT, body], [VERSION_FILE, versionModule]]) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) throw new Error(`Regenerate ${file}: node scripts/generate_lucide_subset.mjs`);
  } else fs.writeFileSync(file, content);
}
console.log(`Lucide subset: ${used.size} icons, ${(Buffer.byteLength(body) / 1024).toFixed(1)} KB (full ${(fs.statSync(FULL).size / 1024).toFixed(1)} KB).`);
