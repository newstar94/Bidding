def _create_trigger_functions(cursor) -> None:
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_validate_workspace_owner()
           RETURNS trigger LANGUAGE plpgsql AS $$
           BEGIN
             IF NEW.owner_type = 'organization' AND NOT EXISTS (
               SELECT 1 FROM to_chuc WHERE id = NEW.organization_id
             ) THEN
               RAISE EXCEPTION 'organization workspace does not exist'
                 USING ERRCODE = '23514';
             ELSIF NEW.owner_type = 'personal' AND NOT EXISTS (
               SELECT 1 FROM tai_khoan
               WHERE id = substring(NEW.organization_id FROM 10)
                 AND vai_tro <> 'super_admin'
             ) THEN
               RAISE EXCEPTION 'personal workspace owner does not exist'
                 USING ERRCODE = '23514';
             END IF;
             RETURN NEW;
           END $$"""
    )
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_set_lineage()
           RETURNS trigger LANGUAGE plpgsql AS $$
           BEGIN
             IF TG_OP = 'INSERT' AND (NEW.id_goc IS NULL OR btrim(NEW.id_goc) = '') THEN
               NEW.id_goc := NEW.id;
             ELSIF TG_OP = 'UPDATE'
               AND OLD.id_goc IS NOT NULL AND btrim(OLD.id_goc) <> ''
               AND NEW.id_goc IS DISTINCT FROM OLD.id_goc THEN
               RAISE EXCEPTION 'LINEAGE_IMMUTABLE' USING ERRCODE = '23514';
             END IF;
             RETURN NEW;
           END $$"""
    )
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_touch_synced_row()
           RETURNS trigger LANGUAGE plpgsql AS $$
           DECLARE next_version BIGINT;
           BEGIN
             IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at
                AND COALESCE(NEW.sync_version, 0) = COALESCE(OLD.sync_version, 0)
                AND NEW.organization_id IS NOT NULL AND NEW.organization_id <> '' THEN
               INSERT INTO sync_metadata (organization_id, current_version)
               VALUES (NEW.organization_id, 0)
               ON CONFLICT (organization_id) DO NOTHING;
               UPDATE sync_metadata
               SET current_version = current_version + 1,
                   updated_at = CURRENT_TIMESTAMP
               WHERE organization_id = NEW.organization_id
               RETURNING current_version INTO next_version;
               NEW.sync_version := next_version;
               NEW.updated_at := CURRENT_TIMESTAMP;
             END IF;
             RETURN NEW;
           END $$"""
    )
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_log_synced_delete()
           RETURNS trigger LANGUAGE plpgsql AS $$
           DECLARE next_version BIGINT;
           BEGIN
             IF OLD.organization_id IS NULL OR OLD.organization_id = '' THEN
               RETURN OLD;
             END IF;
             INSERT INTO sync_metadata (organization_id, current_version)
             VALUES (OLD.organization_id, 0)
             ON CONFLICT (organization_id) DO NOTHING;
             UPDATE sync_metadata
             SET current_version = current_version + 1,
                 updated_at = CURRENT_TIMESTAMP
             WHERE organization_id = OLD.organization_id
             RETURNING current_version INTO next_version;
             INSERT INTO deleted_records (
               table_name, record_id, organization_id, deleted_at, delete_version
             ) VALUES (TG_TABLE_NAME, OLD.id, OLD.organization_id, CURRENT_TIMESTAMP, next_version)
             ON CONFLICT (organization_id, table_name, record_id) DO UPDATE SET
               deleted_at = EXCLUDED.deleted_at,
               delete_version = GREATEST(
                 COALESCE(deleted_records.delete_version, 0),
                 COALESCE(EXCLUDED.delete_version, 0)
               );
             RETURN OLD;
           END $$"""
    )
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_validate_record_edit_owner()
           RETURNS trigger LANGUAGE plpgsql AS $$
           BEGIN
             IF NOT EXISTS (SELECT 1 FROM to_chuc WHERE id = NEW.organization_id)
                AND NOT (
                  NEW.organization_id = 'personal:' || NEW.user_id
                  AND EXISTS (
                    SELECT 1 FROM tai_khoan
                    WHERE id = NEW.user_id AND vai_tro <> 'super_admin'
                  )
                ) THEN
               RAISE EXCEPTION 'record ownership workspace does not exist'
                 USING ERRCODE = '23514';
             END IF;
             RETURN NEW;
           END $$"""
    )
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_validate_verified_email_change()
           RETURNS trigger LANGUAGE plpgsql AS $$
           BEGIN
             IF OLD.email_norm IS DISTINCT FROM NEW.email_norm AND NOT EXISTS (
               SELECT 1 FROM pending_email_changes pending
               WHERE pending.user_id = OLD.id
                 AND pending.current_email_norm = OLD.email_norm
                 AND pending.pending_email_norm = NEW.email_norm
                 AND pending.pending_email = NEW.email
                 AND pending.verified_at IS NOT NULL
                 AND pending.verified_at <= pending.expires_at
                 AND extract(epoch FROM CURRENT_TIMESTAMP)::BIGINT < pending.expires_at
             ) THEN
               RAISE EXCEPTION 'verified email change required'
                 USING ERRCODE = '23514';
             END IF;
             RETURN NEW;
           END $$"""
    )
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_validate_assignment_target()
           RETURNS trigger LANGUAGE plpgsql AS $$
           BEGIN
             IF NEW.loai_doi_tuong NOT IN ('kehoach', 'goithau', 'hopdong')
                OR (NEW.loai_doi_tuong = 'kehoach' AND NOT EXISTS (
                  SELECT 1 FROM ke_hoach_lcnt WHERE organization_id = NEW.organization_id AND id = NEW.id_muc_tieu
                ))
                OR (NEW.loai_doi_tuong = 'goithau' AND NOT EXISTS (
                  SELECT 1 FROM goi_thau WHERE organization_id = NEW.organization_id AND id = NEW.id_muc_tieu
                ))
                OR (NEW.loai_doi_tuong = 'hopdong' AND NOT EXISTS (
                  SELECT 1 FROM hop_dong WHERE organization_id = NEW.organization_id AND id = NEW.id_muc_tieu
                )) THEN
               RAISE EXCEPTION 'ASSIGNMENT_TENANT_MISMATCH' USING ERRCODE = '23514';
             END IF;
             RETURN NEW;
           END $$"""
    )
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_validate_contract_package()
           RETURNS trigger LANGUAGE plpgsql AS $$
           BEGIN
             IF NOT EXISTS (
               SELECT 1
               FROM hop_dong hd
               JOIN ke_hoach_lcnt hdkh
                 ON hdkh.organization_id = hd.organization_id AND hdkh.id = hd.ke_hoach_id
               JOIN goi_thau gt
                 ON gt.organization_id = NEW.organization_id AND gt.id = NEW.goi_thau_id
               JOIN ke_hoach_lcnt gtkh
                 ON gtkh.organization_id = gt.organization_id AND gtkh.id = gt.ke_hoach_id
               WHERE hd.organization_id = NEW.organization_id
                 AND hd.id = NEW.hop_dong_id
                 AND hd.archived_at IS NULL AND gt.archived_at IS NULL
                 AND COALESCE(NULLIF(hdkh.id_goc, ''), hdkh.id)
                   = COALESCE(NULLIF(gtkh.id_goc, ''), gtkh.id)
             ) THEN
               RAISE EXCEPTION 'CONTRACT_PACKAGE_BUSINESS_MISMATCH' USING ERRCODE = '23514';
             END IF;
             RETURN NEW;
           END $$"""
    )
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_forbid_audit_mutation()
           RETURNS trigger LANGUAGE plpgsql AS $$
           BEGIN
             RAISE EXCEPTION 'AUDIT_LOG_IMMUTABLE' USING ERRCODE = '23514';
           END $$"""
    )


