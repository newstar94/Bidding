def _is_boolean_definition(definition: str) -> bool:
    compact = re.sub(r"\s+", "", definition.casefold())
    return "in(0,1)" in compact


def _strip_sqlite_type_checks(definition: str) -> str:
    definition = re.sub(
        r"typeof\([a-zA-Z0-9_]+\)\s*=\s*'integer'\s+AND\s+",
        "",
        definition,
        flags=re.IGNORECASE,
    )
    definition = re.sub(
        r"typeof\([a-zA-Z0-9_]+\)\s+IN\s*\(\s*'integer'\s*,\s*'real'\s*\)\s+AND\s+",
        "",
        definition,
        flags=re.IGNORECASE,
    )
    return definition


def postgres_column_definition(table_name: str, column_name: str, definition: str) -> str:
    """Translate a canonical column declaration without retaining SQLite quirks."""

    result = str(definition)
    if column_name == "extension_json" and "json_valid" in result:
        return (
            "TEXT NOT NULL DEFAULT '{\"schemaVersion\":1}' "
            "CHECK(jsonb_typeof(extension_json::jsonb) IS NOT NULL "
            "AND pg_column_size(extension_json) <= 65536)"
        )
    if "INTEGER PRIMARY KEY AUTOINCREMENT" in result:
        return result.replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        )

    result = _strip_sqlite_type_checks(result)
    result = re.sub(
        r"datetime\(\s*'now'\s*\)", "CURRENT_TIMESTAMP", result, flags=re.IGNORECASE
    )
    result = re.sub(
        r"date\(\s*'now'\s*\)", "CURRENT_DATE", result, flags=re.IGNORECASE
    )

    if result.startswith("REAL"):
        result = "NUMERIC(20,4)" + result[len("REAL") :]
    elif result.startswith("INTEGER"):
        if (table_name, column_name) in MONEY_COLUMNS or column_name in _BIGINT_COLUMNS:
            result = "BIGINT" + result[len("INTEGER") :]
        elif _is_boolean_definition(result):
            result = "SMALLINT" + result[len("INTEGER") :]
    elif result.startswith("TEXT"):
        is_date = column_name.startswith("ngay_") or column_name == "document_date"
        is_timestamp = (
            column_name in _SYSTEM_TIMESTAMP_COLUMNS
            or (table_name, column_name) in _BUSINESS_TIMESTAMP_COLUMNS
        )
        if is_date:
            result = "DATE" + result[len("TEXT") :]
            result = re.sub(
                rf"\s+CHECK\(date\({re.escape(column_name)}\) IS NOT NULL\)",
                "",
                result,
                flags=re.IGNORECASE,
            )
            result = re.sub(
                rf"\s+CHECK\({re.escape(column_name)} IS NULL OR \(length\({re.escape(column_name)}\) = 10 AND date\({re.escape(column_name)}\) IS NOT NULL\)\)",
                "",
                result,
                flags=re.IGNORECASE,
            )
        elif is_timestamp:
            result = "TIMESTAMPTZ" + result[len("TEXT") :]

    result = result.replace("DEFAULT (CURRENT_TIMESTAMP)", "DEFAULT CURRENT_TIMESTAMP")
    result = result.replace("DEFAULT (CURRENT_DATE)", "DEFAULT CURRENT_DATE")
    return re.sub(r"\s+", " ", result).strip()


def postgres_table_constraint(table_name: str, constraint: str) -> str:
    """Translate date/time checks that relied on SQLite coercion functions."""

    result = str(constraint)
    table_columns = SCHEMA_DINH_NGHIA[table_name]["columns"]
    date_columns = {
        name for name in table_columns if name.startswith("ngay_")
    }
    timestamp_columns = {
        name
        for name in table_columns
        if name in _SYSTEM_TIMESTAMP_COLUMNS
        or (table_name, name) in _BUSINESS_TIMESTAMP_COLUMNS
    }
    for column_name in sorted(date_columns | timestamp_columns, key=len, reverse=True):
        escaped = re.escape(column_name)
        result = re.sub(
            rf"NULLIF\(\s*{escaped}\s*,\s*''\s*\)",
            column_name,
            result,
            flags=re.IGNORECASE,
        )
        result = re.sub(
            rf"COALESCE\(\s*trim\(\s*{escaped}\s*\)\s*,\s*''\s*\)\s*=\s*''",
            f"{column_name} IS NULL",
            result,
            flags=re.IGNORECASE,
        )
        result = re.sub(
            rf"COALESCE\(\s*trim\(\s*{escaped}\s*\)\s*,\s*''\s*\)\s*!=\s*''",
            f"{column_name} IS NOT NULL",
            result,
            flags=re.IGNORECASE,
        )
        result = re.sub(
            rf"(?:date|datetime)\(\s*{escaped}\s*\)",
            column_name,
            result,
            flags=re.IGNORECASE,
        )
    return result


def build_create_table_sql(table_name: str, table_spec: dict) -> str:
    columns = []
    primary_keys = tuple(table_spec.get("primary_keys", ()))
    for column_name, sqlite_definition in table_spec["columns"].items():
        definition = postgres_column_definition(
            table_name, column_name, sqlite_definition
        )
        if primary_keys and column_name in primary_keys:
            definition = re.sub(r"\bPRIMARY KEY\b", "", definition).strip()
        columns.append(f"{column_name} {definition}")
    if primary_keys:
        columns.append(f"PRIMARY KEY ({', '.join(primary_keys)})")
    columns.extend(
        postgres_table_constraint(table_name, constraint)
        for constraint in table_spec.get("unique_constraints", ())
    )
    columns.extend(
        postgres_table_constraint(table_name, constraint)
        for constraint in table_spec.get("foreign_keys", ())
        if not constraint.lstrip().upper().startswith("FOREIGN KEY")
    )
    return f"CREATE TABLE {table_name} ({', '.join(columns)})"


def _foreign_key_name(table_name: str, index: int, definition: str) -> str:
    digest = sha256(definition.encode("utf-8")).hexdigest()[:8]
    return f"fk_{table_name}_{index}_{digest}"[:63]


def _create_foreign_keys(
    cursor,
    table_names=None,
    *,
    if_not_exists=False,
) -> None:
    selected_tables = (
        tuple(SCHEMA_DINH_NGHIA)
        if table_names is None
        else tuple(table_names)
    )
    for table_name in selected_tables:
        table_spec = SCHEMA_DINH_NGHIA[table_name]
        foreign_keys = [
            constraint
            for constraint in table_spec.get("foreign_keys", ())
            if constraint.lstrip().upper().startswith("FOREIGN KEY")
        ]
        for index, definition in enumerate(foreign_keys, 1):
            name = _foreign_key_name(table_name, index, definition)
            if if_not_exists:
                cursor.execute(
                    f"""DO $$
                        BEGIN
                          IF NOT EXISTS (
                              SELECT 1 FROM pg_constraint
                              WHERE conrelid = '{table_name}'::regclass
                                AND conname = '{name}'
                          ) THEN
                            ALTER TABLE {table_name}
                                ADD CONSTRAINT {name} {definition};
                          END IF;
                        END $$"""
                )
            else:
                cursor.execute(
                    f"ALTER TABLE {table_name} ADD CONSTRAINT {name} {definition}"
                )


def _create_extensions(cursor) -> None:
    cursor.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm")
    cursor.execute("CREATE EXTENSION IF NOT EXISTS unaccent")
    cursor.execute(
        """CREATE OR REPLACE FUNCTION bf_unaccent(value TEXT)
           RETURNS TEXT LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT AS $$
             SELECT public.unaccent('public.unaccent', value)
           $$"""
    )


