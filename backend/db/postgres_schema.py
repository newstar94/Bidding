def initialize_postgres_database(database) -> int:
    connection = None
    try:
        connection = database.get_connection()
        cursor = connection.cursor()
        cursor.execute("BEGIN")
        cursor.execute(
            "SELECT pg_advisory_xact_lock(hashtext('biddingflow-schema-upgrade'))"
        )
        context = DatabaseUpgradeContext(
            build_create_table_sql=build_create_table_sql,
            create_indexes_and_triggers=create_indexes_and_triggers,
            assert_foreign_key_integrity=assert_foreign_key_integrity,
            create_foreign_keys=_create_foreign_keys,
        )
        installed_version = read_database_version(cursor)
        if installed_version is None:
            version = create_fresh_database(cursor, context)
        else:
            version = apply_database_upgrades(cursor, installed_version, context)
        if version != DB_SCHEMA_VERSION:
            raise RuntimeError(
                f"Database initialization stopped at unexpected version {version}."
            )
        assert_schema_contract(cursor)
        assert_foreign_key_integrity(cursor)
        connection.commit()
        return version
    except Exception:
        if connection is not None:
            connection.rollback()
        raise
    finally:
        if connection is not None:
            connection.close()


def initialize_and_log(database) -> None:
    try:
        version = initialize_postgres_database(database)
        log_error(
            f"PostgreSQL schema ready (version {version}).",
            "Database",
            level="INFO",
        )
    except Exception as exc:
        log_error(exc, "Database.Migration")
        raise
