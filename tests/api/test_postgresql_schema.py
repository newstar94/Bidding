def test_postgresql_search_filter_matches_index_expression_and_tokenizes_input():
    compiled = compile_postgresql_baseline()
    index = next(
        statement
        for statement in compiled["indexes"]
        if "idx_chu_dau_tu_search_trgm" in statement
    )
    expression, parameters = build_postgresql_search_filter(
        "chu_dau_tu", "Nguyễn   Trãi"
    )
    assert parameters == [
        "(^|[[:space:][:punct:]])nguyen",
        "(^|[[:space:][:punct:]])trai",
    ]
    assert expression.count("bidding_immutable_unaccent(lower(") == 2
    indexed_expression = index.split(" USING GIN (", 1)[1].rsplit(" gin_trgm_ops", 1)[0]
    assert indexed_expression in expression


def test_postgresql_manifest_covers_every_sqlite_index_and_trigger(
    monkeypatch, tmp_path
):
    source_database = SQLiteDatabase(tmp_path / "source-manifest.db")
    monkeypatch.setattr(db_utils, "database", source_database)
    monkeypatch.setenv("ADMIN_PASSWORD", "Temporary-Manifest-Test-2026!")
    monkeypatch.setenv("ADMIN_EMAIL", "manifest@example.test")
    db_utils.khoi_tao_va_di_tru_he_thong()
    connection = source_database.get_connection()
    try:
        sqlite_indexes = {
            row[0]
            for row in connection.execute(
                """SELECT name FROM sqlite_master
                   WHERE type = 'index' AND name NOT LIKE 'sqlite_autoindex_%'"""
            ).fetchall()
        }
        sqlite_triggers = {
            row[0]
            for row in connection.execute(
                "SELECT name FROM sqlite_master WHERE type = 'trigger'"
            ).fetchall()
        }
    finally:
        connection.close()

    compiled = compile_postgresql_baseline()
    postgresql_indexes = {
        re.search(r"INDEX\s+([A-Za-z0-9_]+)", statement, re.IGNORECASE).group(1)
        for statement in compiled["indexes"]
    }
    target_artifacts = postgresql_indexes | {
        re.search(r"TRIGGER\s+([A-Za-z0-9_]+)", statement, re.IGNORECASE).group(1)
        for statement in compiled["triggers"]
    }
    trigger_mapping = build_postgresql_trigger_source_map()

    assert sqlite_indexes <= postgresql_indexes
    assert set(trigger_mapping) == sqlite_triggers
    assert set(trigger_mapping.values()) <= target_artifacts
