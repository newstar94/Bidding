def test_postgresql_baseline_covers_every_canonical_table_and_column():
    compiled = compile_postgresql_baseline()
    expected_schema = {**SCHEMA_DINH_NGHIA, **POSTGRESQL_EXTRA_TABLES}
    assert set(compiled["manifest"]) == set(expected_schema)
    assert len(compiled["createTables"]) == len(expected_schema) == 45
    for table_name, table_spec in expected_schema.items():
        assert set(compiled["manifest"][table_name]["columns"]) == set(
            table_spec["columns"]
        )


def test_postgresql_baseline_has_no_sqlite_only_ddl_tokens():
    compiled = compile_postgresql_baseline()
    ddl = "\n".join(
        compiled["createTables"] + compiled["foreignKeys"] + compiled["indexes"]
    )
    forbidden = (
        "AUTOINCREMENT",
        "typeof(",
        "datetime(",
        "date(",
        " AS BLOB",
        "PRAGMA",
        "sqlite_",
    )
    for token in forbidden:
        assert token.casefold() not in ddl.casefold()
    assert "GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "idx_audit_log_single_successor" in ddl


def test_postgresql_money_columns_are_bigint_and_constraints_are_named():
    compiled = compile_postgresql_baseline()
    for table_name, column_name in MONEY_COLUMNS:
        definition = compiled["manifest"][table_name]["columns"][column_name]
        assert definition.startswith("BIGINT")
    names = [
        item["name"]
        for table in compiled["manifest"].values()
        for item in table["foreignKeys"]
    ]
    assert len(names) == len(set(names))
    assert all(re.fullmatch(r"[a-z0-9_]{1,63}", name) for name in names)


